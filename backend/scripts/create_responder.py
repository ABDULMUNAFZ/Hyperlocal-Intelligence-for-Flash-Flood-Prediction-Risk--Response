#!/usr/bin/env python3
"""
Provision a FloodGuard responder account (admin or disaster_manager).

Self-registration always creates `public` users, so responder accounts are created here,
server-side, by someone with access to the backend.

  python scripts/create_responder.py --email ops@example.org --role admin
      → prompts for a password

  python scripts/create_responder.py --email ops@floodguard.local --role admin --generate-dev-password
      → LOCAL DEVELOPMENT ONLY: generates a random password and writes the credentials to
        .cache/dev_responder.json (gitignored). Never use this in production.
"""

import argparse
import asyncio
import getpass
import json
import secrets
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from sqlalchemy import select  # noqa: E402

from app.api.v1.endpoints.auth import get_password_hash  # noqa: E402
from app.db.session import async_session_maker, init_db  # noqa: E402
from app.models.core import User  # noqa: E402


async def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--email", required=True)
    ap.add_argument("--role", choices=["admin", "disaster_manager"], default="disaster_manager")
    ap.add_argument("--name", default="FloodGuard Responder")
    ap.add_argument("--generate-dev-password", action="store_true")
    args = ap.parse_args()

    if args.generate_dev_password:
        password = secrets.token_urlsafe(18)
    else:
        password = getpass.getpass("Password (min 12 chars): ")
        if len(password) < 12:
            print("Password too short", file=sys.stderr)
            return 1

    await init_db()
    async with async_session_maker() as db:
        user = (await db.execute(select(User).where(User.email == args.email))).scalar_one_or_none()
        if user:
            user.role = args.role
            user.hashed_password = get_password_hash(password)
            user.is_active = True
        else:
            user = User(email=args.email, hashed_password=get_password_hash(password), full_name=args.name,
                        role=args.role, is_active=True, is_verified=True)
            db.add(user)
        await db.commit()

    if args.generate_dev_password:
        out = Path(__file__).resolve().parent.parent / ".cache" / "dev_responder.json"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps({"email": args.email, "password": password, "role": args.role,
                                   "note": "LOCAL DEVELOPMENT ONLY — generated by scripts/create_responder.py"}, indent=2))
        out.chmod(0o600)
        print(f"Responder {args.email} ({args.role}) ready; dev credentials written to {out}")
    else:
        print(f"Responder {args.email} ({args.role}) ready.")
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
